import {
	chmod,
	copyFile,
	mkdir,
	readFile,
	rm,
	unlink,
	writeFile,
} from "node:fs/promises";
import { constants } from "node:fs";
import { basename, dirname, join } from "node:path";
import type { VmConfig } from "./config";
import { checked, CliError, Libvirt, run } from "./libvirt";

function quote(value: string): string {
	return `'${value.replaceAll("'", `'\\''`)}'`;
}

async function requirePath(path: string, description: string): Promise<void> {
	if (!(await Bun.file(path).exists()))
		throw new CliError(`${description} not found: ${path}`);
}

async function ensureSshKey(config: VmConfig): Promise<void> {
	const privateKey = config.publicKeyPath.replace(/\.pub$/, "");
	if (
		(await Bun.file(privateKey).exists()) &&
		(await Bun.file(config.publicKeyPath).exists())
	)
		return;
	await mkdir(dirname(privateKey), { recursive: true, mode: 0o700 });
	await checked([
		"ssh-keygen",
		"-q",
		"-t",
		"ed25519",
		"-N",
		"",
		"-f",
		privateKey,
		"-C",
		"vm-manager",
	]);
}

async function prepareArchiveCache(config: VmConfig): Promise<void> {
	const archiveDir = join(config.hostSharedDir, "apt-archives");
	await mkdir(join(archiveDir, "partial"), { recursive: true, mode: 0o777 });
	await chmod(archiveDir, 0o777);
	await chmod(join(archiveDir, "partial"), 0o777);
	const lock = join(archiveDir, "lock");
	await Bun.write(lock, "");
	await chmod(lock, 0o666);
}

async function ensureNetwork(config: VmConfig): Promise<void> {
	await checked(["virsh", "-c", config.uri, "net-autostart", config.network]);
	const info = await checked([
		"virsh",
		"-c",
		config.uri,
		"net-info",
		config.network,
	]);
	if (!/^Active:\s+yes$/m.test(info)) {
		await checked(["virsh", "-c", config.uri, "net-start", config.network]);
	}
	const xml = await checked([
		"virsh",
		"-c",
		config.uri,
		"net-dumpxml",
		config.network,
	]);
	const existingHost = xml.match(
		new RegExp(`<host[^>]*mac=['\"]${config.baseMac}['\"][^>]*/>`),
	)?.[0];
	if (
		existingHost &&
		!existingHost.includes(`ip='${config.baseIp}'`) &&
		!existingHost.includes(`ip=\"${config.baseIp}\"`)
	) {
		throw new CliError(
			`DHCP reservation conflict for ${config.baseMac}: ${existingHost}`,
		);
	}
	if (!existingHost) {
		await checked([
			"virsh",
			"-c",
			config.uri,
			"net-update",
			config.network,
			"add",
			"ip-dhcp-host",
			`<host mac='${config.baseMac}' ip='${config.baseIp}' name='debian13-kde'/>`,
			"--live",
			"--config",
		]);
	}
}

